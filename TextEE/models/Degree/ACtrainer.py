import os, re, logging, tqdm, pprint
from collections import defaultdict
import torch
import numpy as np
from torch.utils.data import DataLoader
from torch.optim import AdamW
from transformers import BartTokenizer, AutoTokenizer, get_linear_schedule_with_warmup

from ..ACtrainer import EAEACMixin
from .ACmodel import DegreeACModel
from .EAEtrainer import DegreeEAETrainer, EAE_collate_fn, get_span_idx
from .pattern import patterns, ROLE_PH_MAP

logger = logging.getLogger(__name__)


class DegreeACTrainer(EAEACMixin, DegreeEAETrainer):
    """AC trainer for Degree (BART-based, with prompt-group chunking).

    Supports `config.prompt_groups`: a list of `{"roles": [...], "length_penalty": float}`
    entries that partition each event type's `valid roles` into chunks. Each chunk
    becomes its own (input, target) pair, keeping inputs/targets short enough
    for BART when an event has many roles. With prompt_groups unset, falls
    back to one prompt per instance covering all valid roles.

    The dataset's prose `EAE template` is replaced with a flat per-chunk
    template (`{ROLE_R1} . {ROLE_R2} . ...`) so chunks can be assembled and
    decoded without parsing the original templates.
    """

    # ---------------------------- model wiring ----------------------------

    def load_model(self, checkpoint=None):
        """Mirror of DegreeEAETrainer.load_model but instantiates DegreeACModel."""
        if checkpoint:
            logger.info(f"Loading model from {checkpoint}")
            state = torch.load(os.path.join(checkpoint, "best_model.state"),
                               map_location=f'cuda:{self.config.gpu_device}',
                               weights_only=False)
            self.tokenizer = state["tokenizer"]
            self.type_set = state["type_set"]
            self.model = DegreeACModel(self.config, self.tokenizer, self.type_set)
            self.model.load_state_dict(state['model'])
            self.model.cuda(device=self.config.gpu_device)
        else:
            logger.info(f"Loading model from {self.config.pretrained_model_name}")
            if os.path.basename(str(self.config.pretrained_model_name)).startswith('facebook/bart-'):
                self.tokenizer = BartTokenizer.from_pretrained(
                    self.config.pretrained_model_name, cache_dir=self.config.cache_dir)
            else:
                self.tokenizer = AutoTokenizer.from_pretrained(
                    self.config.pretrained_model_name, cache_dir=self.config.cache_dir, use_fast=False)

            special_tokens = ['<Trigger>', '<sep>', '<None>']
            logger.info(f"Add tokens {special_tokens}")
            self.tokenizer.add_tokens(special_tokens)
            self.model = DegreeACModel(self.config, self.tokenizer, self.type_set)
            self.model.cuda(device=self.config.gpu_device)

        self.generate_vocab()

    # -------------------------- prompt-group split ------------------------

    _ENUM_SUFFIX_RE = re.compile(r'\d+$')

    @property
    def _schema_role_set(self):
        """All role names declared in the dataset schema, cached per trainer.

        Sourced from `config.key_map["structure"]` — main factors and their
        sub-factors. These are the role names that exist in the original
        annotation schema, BEFORE `generate_valid_patterns.py` synthesizes
        enumerated variants (work_ctx2, work_ctx3, ...).

        Used by `_base_role` to distinguish schema roles (leave alone) from
        auto-enumerated ones (strip digit suffix to recover the base).
        Falls back to `type_set["role"]` when key_map.structure is missing
        — adequate for datasets that don't ship a structure block.
        """
        cached = getattr(self, "_cached_schema_role_set", None)
        if cached is not None:
            return cached
        key_map = getattr(self.config, "key_map", None) or {}
        structure = key_map.get("structure", {}) or {}
        roles = set()
        for mf in structure.get("accident_report", []) or []:
            roles.add(mf)
            for sk in structure.get(mf, []) or []:
                roles.add(sk)
        if not roles:
            roles = set((getattr(self, "type_set", None) or {}).get("role", []) or [])
        self._cached_schema_role_set = roles
        return roles

    def _base_role(self, role):
        """Schema-aware base-role lookup for enumerated role names.

        Resolution order:
          1. `patterns[dataset]["role_alias"]` — the authoritative
             enum→base map generated by `generate_valid_patterns.py`,
             nested inside the dataset's patterns block alongside event
             entries. Includes only auto-synthesized names (e.g.
             `work_ctx2`); schema-native roles are absent.
          2. Otherwise check schema set: if `role` is a schema base
             (or `role_alias` isn't generated yet), return unchanged.
          3. Otherwise strip trailing digits — last-resort fallback for
             cases where the alias map wasn't generated.
        """
        ds_block = patterns.get(self.config.dataset, {}) or {}
        ds_alias = ds_block.get("role_alias", {}) if isinstance(ds_block, dict) else {}
        if role in ds_alias:
            return ds_alias[role]
        if role in self._schema_role_set:
            return role
        return self._ENUM_SUFFIX_RE.sub('', role)

    # -------------------------- pass-level stats --------------------------

    @staticmethod
    def _new_cutoff_stats():
        """Slot-cutoff accumulator for one full eval pass."""
        return {
            "n_chunks_total":         0,
            "n_chunks_cutoff":        0,
            "missing_slots_per_role": defaultdict(int),
            "total_slots_per_role":   defaultdict(int),
        }

    def _log_cutoff_stats(self, cutoff, split, level=logging.INFO):
        """One-line summary + per-role breakdown. Silent when no cutoff.

        Logged at INFO by default; the per-call path in `_predict_batch`
        passes DEBUG so direct calls don't flood. `predictAC` aggregates
        across all per-doc calls and logs once at INFO at end-of-pass.
        """
        n_total = cutoff["n_chunks_total"]
        n_cut   = cutoff["n_chunks_cutoff"]
        if not n_total or not n_cut:
            return
        pct = 100.0 * n_cut / n_total
        logger.log(level,
                   f"[{split}] slot-cutoff: {n_cut}/{n_total} chunks "
                   f"({pct:.1f}%) had at least one missing slot — output "
                   f"likely truncated at max_output_length="
                   f"{self.config.max_output_length}.")
        role_lines = ", ".join(
            f"{r}={cutoff['missing_slots_per_role'][r]}/"
            f"{cutoff['total_slots_per_role'][r]}"
            for r in sorted(cutoff["missing_slots_per_role"],
                            key=lambda r: -cutoff["missing_slots_per_role"][r])
        )
        logger.log(level, f"[{split}] slot-cutoff misses per role: {role_lines}")

    def predictAC(self, data, **kwargs):
        """Override to aggregate `_predict_batch` span-match + slot-cutoff
        stats across every per-doc call in the eval pass, and emit a single
        end-of-pass summary at INFO. Also seeds the per-pass sample-print
        counter so the first few model outputs get logged for debugging.

        Without this wrapper, `_predict_batch` would either fire 53× per
        dev pass (one log per doc — flood) or stay quiet at DEBUG (useful
        signal hidden).
        """
        self._ac_span_stats     = self.new_span_match_stats()
        self._ac_cutoff_stats   = self._new_cutoff_stats()
        self._ac_samples_logged = 0
        # config.debug toggles sample-print on/off; config.debug_limit caps
        # how many sample triples per eval pass (default 3 when debug=true).
        debug_on = bool(getattr(self.config, "debug", False))
        self._ac_max_samples = (int(getattr(self.config, "debug_limit", 3) or 0)
                                if debug_on else 0)
        try:
            return super().predictAC(data, **kwargs)
        finally:
            self.log_span_match_stats(self._ac_span_stats, split="AC")
            self._log_cutoff_stats(self._ac_cutoff_stats, split="AC")
            self._ac_span_stats     = None
            self._ac_cutoff_stats   = None
            self._ac_samples_logged = None
            self._ac_max_samples    = None

    def _resolve_prompt_chunks(self, full_role_list):
        """Partition `full_role_list` into chunks based on `config.prompt_groups`.

        Each group's listed roles match any role in `full_role_list` whose
        base (digits stripped) equals a listed role — so config `["work_ctx"]`
        automatically covers `work_ctx`, `work_ctx2`, `work_ctx3`, ...

        Returns `[(group_idx, role_list), ...]`, preserving the order of
        roles as they appear in `full_role_list`. group_idx is -1 for the
        fallback chunk (and when prompt_groups is unset).
        """
        prompt_groups = list(getattr(self.config, "prompt_groups", []) or [])
        if not prompt_groups:
            return [(-1, list(full_role_list))]

        used = set()
        chunks = []
        for gi, group in enumerate(prompt_groups):
            group_roles = set(group.get("roles", []) if isinstance(group, dict) else group)
            chunk = [r for r in full_role_list
                     if r not in used
                     and (r in group_roles or self._base_role(r) in group_roles)]
            if chunk:
                chunks.append((gi, chunk))
                used.update(chunk)
        rest = [r for r in full_role_list if r not in used]
        if rest:
            chunks.append((-1, rest))
        return chunks

    # ---------------------------- chunk template --------------------------

    _ROLE_PH_RE = re.compile(r'\{ROLE_(\w+)\}')

    def _template_role_set(self, event_type):
        """All roles whose `{ROLE_X}` placeholder appears in the template."""
        template = patterns[self.config.dataset][event_type]["AC template"]
        return set(self._ROLE_PH_RE.findall(template))

    def _chunk_template(self, event_type, chunk_roles):
        """Return the dataset's EAE template, optionally chunked.

        - If `chunk_roles` covers EVERY placeholder in the template (no split,
          or split that happens to keep all roles together), the template is
          returned VERBATIM — no labels invented, no spacing normalized.
        - Otherwise, walk by `{ROLE_X}` matches: each segment from the prior
          match end through this placeholder is that role's "label + placeholder";
          keep it whole if X is in chunk_roles, drop it whole otherwise.
        """
        template = patterns[self.config.dataset][event_type]["AC template"]
        if self._template_role_set(event_type) <= set(chunk_roles):
            return template
        chunk_set = set(chunk_roles)
        out = []
        cursor = 0
        for m in self._ROLE_PH_RE.finditer(template):
            if m.group(1) in chunk_set:
                out.append(template[cursor:m.end()])
            cursor = m.end()
        out.append(template[cursor:])
        return ''.join(out).strip()

    def _chunk_pairs(self, event_type, chunk_roles):
        """`(label, role)` pairs in template order, restricted to chunk_roles.
        Used by `_decode_chunk` to find each role's span by locating its
        label substring in the predicted text.
        """
        template = patterns[self.config.dataset][event_type]["AC template"]
        parts = self._ROLE_PH_RE.split(template)
        # parts = [pre_1, R1, between_1_2, R2, ..., Rn, post_n]
        chunk_set = set(chunk_roles)
        pairs = []
        for i in range(1, len(parts), 2):
            label = parts[i - 1].strip()
            role = parts[i]
            if role in chunk_set:
                pairs.append((label, role))
        return pairs

    def _chunk_input_template(self, event_type, chunk_roles):
        """Chunked template with placeholders filled by ROLE_PH_MAP defaults
        — for the encoder prompt.
        """
        ph_map = ROLE_PH_MAP[self.config.dataset]
        return self._chunk_template(event_type, chunk_roles).format(**{
            f"ROLE_{r}": ph_map.get(f"ROLE_{r}", f"some {r}")
            for r in chunk_roles
        })

    def _chunk_target(self, event_type, tokens, arguments, chunk_roles):
        """Chunked template filled with gold arg text per (enumerated) role.

        With enumerated slots in the static EAE template, each role in
        `chunk_roles` is a distinct slot — `work_ctx`, `work_ctx2`, ... are
        separate roles. Gold args produced by `_convert_ac_record_to_eae`
        also carry enumerated role names, so the mapping is exact: at most
        one gold arg per enumerated slot. Empty slots fall back to the
        ROLE_PH_MAP placeholder so `_decode_chunk` can drop them.
        """
        ph_map = ROLE_PH_MAP[self.config.dataset]
        chunk_set = set(chunk_roles)
        arg_by_role = {}
        for arg in arguments:
            if arg[2] in chunk_set and arg[2] not in arg_by_role:
                arg_by_role[arg[2]] = ' '.join(tokens[arg[0]:arg[1]])
        filler = {}
        for r in chunk_roles:
            key = f"ROLE_{r}"
            if r in arg_by_role:
                filler[key] = arg_by_role[r]
            else:
                filler[key] = ph_map.get(key, f"some {r}")
        return self._chunk_template(event_type, chunk_roles).format(**filler)

    def _decode_chunk(self, event_type, pred_text, chunk_roles):
        """Extract (span_text, base_role) tuples by splitting on role labels.

        Template is `Label_1 X Label_2 Y Label_3 Z` so each role's span lies
        between its own label and the next role's label (or end-of-text for
        the last role). Labels and order come from the dataset's static
        EAE template via `_chunk_pairs`, so this matches whatever
        generate_valid_patterns produced.

        Each enumerated slot is decoded independently, but the output role
        is the **base role** (digits stripped) so multiple slots of the
        same factor collapse back under one key — `ie_preds_to_flat_ac`
        joins same-role entity_mentions with `;` for flat AC scoring.
        """
        pairs = self._chunk_pairs(event_type, chunk_roles)
        ph_map = ROLE_PH_MAP[self.config.dataset]
        text = pred_text.strip()

        out = []
        for i, (label, role) in enumerate(pairs):
            idx = text.find(label)
            if idx == -1:
                continue
            start = idx + len(label)
            # Next role's label is the right boundary; otherwise end of text.
            end = len(text)
            for next_label, _ in pairs[i + 1:]:
                next_idx = text.find(next_label, start)
                if next_idx != -1:
                    end = next_idx
                    break
            span = text[start:end].strip()
            if not span:
                continue
            ph = ph_map.get(f"ROLE_{role}", f"some {role}")
            if span == ph:
                continue
            base = self._base_role(role)
            out.append((span, base))
        return out

    # ---------------------- input string assembly -------------------------

    def _build_input_str(self, tokens, trigger, chunk_roles):
        """Assemble the encoder input following config.input_style, with the
        chunk's role template substituted for the dataset's EAE template.

        Mirrors `event_template.generate_input_str` — but uses
        `_chunk_input_template` instead of the static dataset template.
        """
        event_type = trigger[2]
        info = patterns[self.config.dataset][event_type]
        passage = ' '.join(tokens)
        trigger_text = ' '.join(tokens[trigger[0]:trigger[1]]) if trigger[1] > trigger[0] else ''
        SEP = '\n'
        input_str = passage
        for i_style in self.config.input_style:
            if i_style == 'event_type':
                input_str += f' {SEP} {info["event type"]}'
            elif i_style == 'event_type_sent':
                input_str += f' {SEP} {info["event description"]}'
            elif i_style == 'keywords':
                input_str += f' {SEP} Similar triggers such as {", ".join(info["keywords"])}'
            elif i_style == 'triggers':
                input_str += f' {SEP} The event trigger word is {trigger_text}'
            elif i_style == 'template':
                input_str += f' {SEP} {self._chunk_input_template(event_type, chunk_roles)}'
        return input_str

    # ----------------------- process / predict ----------------------------

    def process_data(self, data):
        """One internal instance per (input, chunk).

        For each input event, splits its `valid roles` via prompt_groups and
        emits a separate (input, target) per chunk — same shape as
        XGearACTrainer.process_data so `_predict_batch` and `internal_predict`
        can group/merge by `_prompt_group_idx` / `_orig_wnd_id`.
        """
        assert self.tokenizer, "Please load model and tokenizer before processing data!"

        # Reset chunk-roles cache: needed by _predict_batch since EAE_collate_fn
        # doesn't carry per-instance metadata beyond standard EAE fields.
        self._wnd_chunk_roles = {}

        n_total = 0
        n_drop_length = 0
        # Target-length sanity check: BART's decoder is autoregressive, so
        # any target longer than max_output_length has its tail silently
        # discarded during training (loss is only computed on the truncated
        # prefix). We only count this during training mode — at inference
        # the target is empty so the check would always pass.
        n_overlong_target = 0
        overlong_target_lens = []
        is_train = getattr(self, "_in_train", False)
        new_data = []
        for dt in data:
            n_total += 1
            event_info = patterns[self.config.dataset].get(dt["trigger"][2])
            if not event_info:
                continue
            full_roles = event_info.get("valid roles", [])
            if not full_roles:
                continue

            chunks = self._resolve_prompt_chunks(full_roles)
            chunked = len(chunks) > 1

            for chunk_idx, (group_idx, chunk_roles) in enumerate(chunks):
                input_str = self._build_input_str(dt["tokens"], dt["trigger"], chunk_roles)
                if len(self.tokenizer.tokenize(input_str)) > self.config.max_length:
                    n_drop_length += 1
                    continue
                target_str = self._chunk_target(dt["trigger"][2], dt["tokens"], dt["arguments"], chunk_roles)
                if is_train:
                    target_len = len(self.tokenizer.tokenize(target_str))
                    if target_len > self.config.max_output_length:
                        n_overlong_target += 1
                        overlong_target_lens.append(target_len)

                pieces = [self.tokenizer.tokenize(t) for t in dt["tokens"]]
                token_lens = [len(p) for p in pieces]
                pieces = [p for piece in pieces for p in piece]
                piece_idxs = self.tokenizer.convert_tokens_to_ids(pieces)
                assert sum(token_lens) == len(piece_idxs)
                token_start_idxs = [sum(token_lens[:_]) for _ in range(len(token_lens))] + [sum(token_lens)]

                chunk_wnd_id = (f"{dt['wnd_id']}__chunk{chunk_idx}"
                                if chunked else dt["wnd_id"])
                chunk_set = set(chunk_roles)
                chunk_args = [a for a in dt["arguments"] if a[2] in chunk_set]

                self._wnd_chunk_roles[chunk_wnd_id] = (group_idx, list(chunk_roles))

                new_data.append({
                    "doc_id":            dt["doc_id"],
                    "wnd_id":            chunk_wnd_id,
                    "_orig_wnd_id":      dt["wnd_id"],
                    "_prompt_group_idx": group_idx,
                    "_chunk_roles":      list(chunk_roles),
                    "tokens":            dt["tokens"],
                    "text":              dt["text"],
                    "piece_idxs":        piece_idxs,
                    "token_start_idxs":  token_start_idxs,
                    "trigger":           dt["trigger"],
                    "arguments":         chunk_args,
                    "input":             input_str,
                    "target":            target_str,
                })

        if n_drop_length:
            logger.info(f"[process_data] dropped {n_drop_length}/{n_total} chunks "
                        f"for input > max_length={self.config.max_length}")
        if n_overlong_target:
            avg = float(np.mean(overlong_target_lens))
            mx = max(overlong_target_lens)
            # WARNING (not info): targets aren't dropped — they're still
            # trained on, but the decoder loss only sees the first
            # max_output_length tokens. Bump max_output_length, or pass
            # --max_enum N to generate_valid_patterns.py to shorten the
            # static template.
            logger.warning(
                f"[process_data] {n_overlong_target}/{n_total} train chunks have "
                f"target > max_output_length={self.config.max_output_length} "
                f"(avg={avg:.0f}, max={mx} subwords) — decoder loss is computed "
                f"on the truncated prefix only."
            )
        # debug-level: process_data is called once per document during AC
        # inference, so logging at info would flood the log with one line per
        # doc × per dev eval. Drop counts above stay at info because they're
        # actionable.
        logger.debug(f"Generate {len(new_data)} Degree AC chunked instances "
                     f"from {n_total} EAE instances")
        return new_data

    def _predict_batch(self, eval_data, split="Test"):
        """Group by prompt-group so each batch shares decoding hyperparameters.

        When prompt_groups is unset, every instance has _prompt_group_idx=-1
        and we get a single group with default params — equivalent to the
        un-chunked path.
        """
        groups = defaultdict(list)
        for d in eval_data:
            groups[d.get("_prompt_group_idx", -1)].append(d)
        prompt_groups = list(getattr(self.config, "prompt_groups", []) or [])

        bs = self.config.eval_batch_size
        # No inner tqdm: in hierarchical AC inference, `_predict_batch` is
        # called once per document (via `predict_ac_eae_hierarchical`), so an
        # inner bar would print N times alongside the outer
        # `AC inference [hierarchical]` bar. The outer bar already tracks
        # per-doc progress; this scope is just a few batches per call.
        progress = tqdm.tqdm(total=0, ncols=100, desc=split, disable=True)

        # Drop & cutoff accounting. When `predictAC` initialized pass-level
        # accumulators on the instance, write to those so the summary covers
        # every doc in the eval pass and only prints once at the end.
        # Otherwise (direct call to `_predict_batch`), keep local accumulators
        # and log at the bottom of this function.
        pass_span_stats = getattr(self, "_ac_span_stats", None)
        pass_cutoff_stats = getattr(self, "_ac_cutoff_stats", None)
        own_logging = pass_span_stats is None
        if own_logging:
            stats = self.new_span_match_stats()
            cutoff = self._new_cutoff_stats()
        else:
            stats = pass_span_stats
            cutoff = pass_cutoff_stats

        predictions = []
        for gidx, gdata in groups.items():
            if 0 <= gidx < len(prompt_groups) and isinstance(prompt_groups[gidx], dict):
                length_penalty = float(prompt_groups[gidx].get("length_penalty", 1.0))
            else:
                length_penalty = 1.0

            for batch in DataLoader(gdata, batch_size=bs,
                                    shuffle=False, collate_fn=EAE_collate_fn):
                progress.update(1)
                pred_texts = self.model.predict(
                    batch,
                    num_beams=self.config.beam_size,
                    max_length=self.config.max_output_length,
                    length_penalty=length_penalty,
                )
                for idx, (doc_id, wnd_id, tokens, text, piece_idxs, token_start_idxs, trigger, pred_text) in enumerate(zip(
                        batch.batch_doc_id, batch.batch_wnd_id, batch.batch_tokens, batch.batch_text,
                        batch.batch_piece_idxs, batch.batch_token_start_idxs,
                        batch.batch_trigger, pred_texts)):

                    chunk_roles = self._wnd_chunk_roles.get(wnd_id, (None, []))[1]
                    pred_objects = self._decode_chunk(trigger[2], pred_text, chunk_roles)

                    # Walk labels in template order; once a label is missing,
                    # all subsequent labels are flagged missing too — that's
                    # the cutoff signature. Per-role missing counts use the
                    # base role so accumulated stats stay readable.
                    chunk_pairs = self._chunk_pairs(trigger[2], chunk_roles)
                    cutoff["n_chunks_total"] += 1
                    cursor = 0
                    cutoff_seen = False
                    chunk_has_miss = False
                    for label, role in chunk_pairs:
                        base = self._base_role(role)
                        cutoff["total_slots_per_role"][base] += 1
                        if cutoff_seen:
                            cutoff["missing_slots_per_role"][base] += 1
                            chunk_has_miss = True
                            continue
                        idx = pred_text.find(label, cursor)
                        if idx == -1:
                            cutoff["missing_slots_per_role"][base] += 1
                            chunk_has_miss = True
                            cutoff_seen = True
                        else:
                            cursor = idx + len(label)
                    if chunk_has_miss:
                        cutoff["n_chunks_cutoff"] += 1

                    pred_arguments = []
                    for span, role_type in pred_objects:
                        # Triggerless: no trigger-proximity bias — first
                        # contiguous match in the passage wins. AC's synthetic
                        # trigger lives at token 0, so biasing toward it would
                        # pull every span to the passage start.
                        sid, eid = get_span_idx(piece_idxs, token_start_idxs, span,
                                                self.tokenizer, trigger_span=None)
                        self.record_span_match(stats, role_type, sid != -1)
                        if sid == -1:
                            continue
                        pred_arguments.append((sid, eid, role_type, span))

                    predictions.append({
                        "doc_id":    doc_id,
                        "wnd_id":    wnd_id,
                        "tokens":    tokens,
                        "text":      text,
                        "trigger":   trigger,
                        "arguments": pred_arguments,
                    })

                    # First N sample predictions per eval pass — surfaces
                    # what the model is actually emitting so you can tell
                    # "model is silent" from "model paraphrases" from
                    # "decoder isn't aligning labels". Initialized in
                    # `predictAC`; capped by config.ac_sample_log_count.
                    n_logged = getattr(self, "_ac_samples_logged", 0)
                    n_cap = getattr(self, "_ac_max_samples", 0) or 0
                    if n_logged < n_cap:
                        input_str = batch.batch_input[idx]
                        logger.info(
                            f"[{split} sample {n_logged + 1}/{n_cap}] "
                            f"event={trigger[2]} chunk_roles={chunk_roles}"
                        )
                        logger.info(f"  input  : {input_str[:300]}"
                                    + ("…" if len(input_str) > 300 else ""))
                        logger.info(f"  predict: {pred_text[:300]}"
                                    + ("…" if len(pred_text) > 300 else ""))
                        logger.info(f"  decoded: {pred_objects}")
                        logger.info(f"  spans  : {pred_arguments}")
                        self._ac_samples_logged = n_logged + 1
        progress.close()
        # If `predictAC` set up pass-level accumulators, leave the summary
        # to it (logged once at end of the full eval pass). Otherwise this
        # was a direct `_predict_batch` call — log local stats at debug to
        # stay quiet on the default INFO level.
        if own_logging:
            self.log_span_match_stats(stats, split, level=logging.DEBUG)
            self._log_cutoff_stats(cutoff, split, level=logging.DEBUG)
        return predictions

    def internal_predict(self, data, **kwargs):
        assert self.tokenizer and self.model
        internal_data = self.process_data(data)
        raw_preds = self._predict_batch(internal_data, split="Test")
        # Merge chunked predictions back to one result per input instance.
        wnd_to_orig = {d["wnd_id"]: d.get("_orig_wnd_id", d["wnd_id"]) for d in internal_data}
        merged = {}
        for pred in raw_preds:
            orig = wnd_to_orig.get(pred["wnd_id"], pred["wnd_id"])
            if orig not in merged:
                mp = dict(pred)
                mp["wnd_id"] = orig
                mp["arguments"] = list(pred["arguments"])
                merged[orig] = mp
            else:
                # Different chunks of the same input cover disjoint role sets,
                # so concatenating their argument tuples is correct.
                merged[orig]["arguments"].extend(pred["arguments"])
        return list(merged.values())

    # ------------------------------ train --------------------------------

    def train(self, train_data, dev_data, **kwargs):
        self.load_model()
        # _in_train flag gates the target-length sanity check in process_data
        # — that warning is only meaningful for gold targets during training,
        # not the empty targets used at inference.
        self._in_train = True
        try:
            internal_train_data = self.process_data(train_data)
        finally:
            self._in_train = False

        # Sanity check: every parameter must be finite right after model loading.
        for n, p in self.model.named_parameters():
            if not torch.isfinite(p).all():
                raise RuntimeError(
                    f"Parameter {n} is non-finite immediately after load_model() — "
                    f"either the local checkpoint is corrupt or resize_token_embeddings produced NaN rows.")
        logger.info("[sanity] all model parameters finite at training start.")

        param_groups = [{'params': self.model.parameters(),
                         'lr': self.config.learning_rate,
                         'weight_decay': self.config.weight_decay}]

        train_batch_num = len(internal_train_data) // self.config.train_batch_size + (len(internal_train_data) % self.config.train_batch_size != 0)
        # foreach=False / fused=False: PyTorch 2.x's fused AdamW corrupts BART's tied
        # `shared.weight` (encoder.embed_tokens / decoder.embed_tokens / lm_head all alias it).
        # eps=1e-6: standard for BART fine-tuning; default 1e-8 underflows when bias-corrected
        # second-moment denominator is very small at warmup step 1.
        optimizer = AdamW(params=param_groups, eps=1e-6, foreach=False, fused=False)
        scheduler = get_linear_schedule_with_warmup(
            optimizer,
            num_warmup_steps=train_batch_num * self.config.warmup_epoch,
            num_training_steps=train_batch_num * self.config.max_epoch,
        )

        # Shared save-best + early-stop driver from EAEACMixin: handles the
        # F1-strict-improve / loss-tiebreak save policy AND the
        # config.early_stop_epochs patience counter in one place. `best_state`
        # is owned here; the helper mutates it each epoch.
        best_state = self.make_best_state()

        for epoch in range(1, self.config.max_epoch + 1):
            logger.info(f"Log path: {self.config.log_path}")
            logger.info(f"Epoch {epoch}")

            progress = tqdm.tqdm(total=train_batch_num, ncols=100, desc='Train {}'.format(epoch))
            self.model.train()
            optimizer.zero_grad()
            cummulate_loss = []
            nan_skips = 0
            for batch_idx, batch in enumerate(DataLoader(
                    internal_train_data,
                    batch_size=self.config.train_batch_size // self.config.accumulate_step,
                    shuffle=True, drop_last=False, collate_fn=EAE_collate_fn)):

                loss = self.model(batch)
                # Guard against NaN/Inf — skip the batch entirely so it can't poison weights.
                if not torch.isfinite(loss):
                    if nan_skips == 0:
                        # One-shot diagnostic on the first NaN to identify root cause.
                        logger.warning(f"[NaN-loss] batch_idx={batch_idx}, loss={loss.item()}")
                        logger.warning(f"[NaN-loss] batch sizes: input={[len(s) for s in batch.batch_input]}, target={[len(s) for s in batch.batch_target]}")
                        logger.warning(f"[NaN-loss] sample input  : {batch.batch_input[0][:400]}")
                        logger.warning(f"[NaN-loss] sample target : {batch.batch_target[0][:400]}")
                        for n, p in self.model.named_parameters():
                            if not torch.isfinite(p).all():
                                logger.warning(f"[NaN-loss] non-finite param: {n}  (this is the root cause; the previous step poisoned weights)")
                                break
                        else:
                            logger.warning("[NaN-loss] all weights are finite — NaN comes from forward pass on this specific input")
                    optimizer.zero_grad()
                    nan_skips += 1
                    if (batch_idx + 1) % self.config.accumulate_step == 0:
                        progress.update(1)
                    continue
                loss = loss * (1 / self.config.accumulate_step)
                cummulate_loss.append(loss.item())
                loss.backward()

                if (batch_idx + 1) % self.config.accumulate_step == 0:
                    progress.update(1)
                    # clip_grad_norm_ returns the pre-clip total norm.
                    gnorm = torch.nn.utils.clip_grad_norm_(self.model.parameters(),
                                                           self.config.grad_clipping)
                    # Reject the step if grad contains NaN/Inf — clipping doesn't fix non-finite values,
                    # and a single bad step poisons every weight permanently.
                    if not torch.isfinite(gnorm):
                        optimizer.zero_grad()
                        nan_skips += 1
                        progress.set_postfix(loss="grad-nan", nan=nan_skips)
                        continue
                    optimizer.step()
                    scheduler.step()
                    # Post-step weight check — done BEFORE zero_grad so grads are still inspectable.
                    bad_param = None
                    for n, p in self.model.named_parameters():
                        if not torch.isfinite(p).all():
                            bad_param = n
                            break
                    if bad_param is not None:
                        bad = dict(self.model.named_parameters())[bad_param]
                        if bad.dim() >= 1:
                            row_bad = ~torch.isfinite(bad).reshape(bad.shape[0], -1).all(dim=1)
                            n_bad   = int(row_bad.sum().item())
                            n_total = bad.shape[0]
                            bad_idx = row_bad.nonzero().flatten().tolist()[:30]
                            logger.error(f"[POST-STEP NaN] {bad_param}  shape={tuple(bad.shape)}")
                            logger.error(f"  non-finite rows: {n_bad}/{n_total}")
                            logger.error(f"  first bad row indices: {bad_idx}")
                            old_vocab = getattr(self.tokenizer, "vocab_size", None)
                            tok_len   = len(self.tokenizer)
                            if old_vocab is not None:
                                logger.error(f"  tokenizer.vocab_size={old_vocab}, len(tokenizer)={tok_len}")
                                if all(i >= old_vocab for i in bad_idx):
                                    logger.error("  ⇒ ALL bad rows are NEWLY-ADDED tokens — embedding init / first-step problem.")
                                elif all(i < old_vocab for i in bad_idx):
                                    logger.error("  ⇒ ALL bad rows are pretrained tokens — generic AdamW corruption.")
                                else:
                                    logger.error("  ⇒ Mix of pretrained and new — generic AdamW corruption (cascade).")
                        logger.error(f"  gnorm={gnorm:.4f}, lr={scheduler.get_last_lr()[0]:.2e}")
                        if hasattr(self, "tokenizer") and bad.dim() >= 1:
                            ov = getattr(self.tokenizer, "vocab_size", 0)
                            grad = bad.grad if bad.grad is not None else None
                            if grad is not None and grad.shape[0] > ov:
                                new_rows_grad = grad[ov:].norm(dim=1)
                                old_rows_grad = grad[:ov].norm(dim=1)
                                logger.error(f"  grad norm — new rows: max={new_rows_grad.max():.4e}, mean={new_rows_grad.mean():.4e}")
                                logger.error(f"  grad norm — old rows: max={old_rows_grad.max():.4e}, mean={old_rows_grad.mean():.4e}")
                        progress.close()
                        raise RuntimeError(f"Optimizer step poisoned weights at batch {batch_idx}")
                    optimizer.zero_grad()
                    # Live running-mean loss in the tqdm bar.
                    if cummulate_loss:
                        progress.set_postfix(loss=f"{np.mean(cummulate_loss[-100:]):.4f}",
                                             gnorm=f"{gnorm:.2f}",
                                             nan=nan_skips)

            progress.close()
            avg_loss = float(np.mean(cummulate_loss)) if cummulate_loss else float("nan")
            logger.info(f"[Epoch {epoch}] avg train loss = {avg_loss:.4f}  (nan_skips={nan_skips})")

            dev_f = self._ac_dev_eval(dev_data)
            should_save, should_stop = self._save_best_and_check_early_stop(
                dev_f, avg_loss, epoch, best_state)
            if should_save:
                logger.info("Saving best model")
                state = dict(model=self.model.state_dict(),
                             tokenizer=self.tokenizer, type_set=self.type_set)
                torch.save(state, os.path.join(self.config.output_dir, "best_model.state"))
            if should_stop:
                break
